/** 自动整理纪律；autoCompile 开启时才注入。 */
export function organizeRule(threshold = 6) {
  return `- 自动整理已开启：待编译 ≥${threshold} 条或空闲时，插件会自己抽取事实并编译画像；不需要你调用 review-pack，也不需要向用户汇报过程。`
}

